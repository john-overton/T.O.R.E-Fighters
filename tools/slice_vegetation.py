    ('desert_stones',(431,525,613,650)), ('broadleaf',(660,59,902,347)),
    ('autumn',(902,59,1115,345)), ('birch',(1116,70,1327,347)),
    ('green_bush',(670,360,834,506)), ('red_bush',(833,351,997,506)),
    ('sparse_bush',(996,340,1159,518)), ('conifer',(1161,325,1338,519)),
    ('mossy_boulder',(670,496,920,657)), ('mossy_rock',(925,519,1075,650)),
    ('flat_rock',(1078,537,1259,658)), ('palm_a',(1380,50,1627,350)),
    ('palm_b',(1628,61,1790,350)), ('jungle_tree',(1789,63,2047,353)),
    ('banana',(1371,347,1573,528)), ('fern',(1576,360,1740,516)),

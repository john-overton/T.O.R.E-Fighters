def clean(image):
    """Remove near-black matte and generator chroma, including interior holes."""
    image = image.convert('RGBA')
    pixels = []
    for r, g, b, a in image.getdata():
        key = max(r,g,b) < 24 or a < 128
        fringe = (r > 120 and g < 65 and b < 65 and r > 3 * max(g,1)) or (g > 65 and r < 35 and b < 35)
        # Pure yellow perimeter speckle is also present on the desert shrub.
        fringe |= r > 200 and g > 200 and b < 40
        pixels.append((0,0,0,0) if key or fringe else (r,g,b,255))
    image.putdata(pixels)
    # Reject isolated generator specks, retain connected trunks and thin leaves.
    alpha = image.getchannel('A')
    core = alpha.filter(ImageFilter.MinFilter(3)).filter(ImageFilter.MaxFilter(3))
    # Drop isolated crop-boundary lines and generator debris. Keep secondary
    # stones/leaves only when they are substantial connected components.
    mask = bytearray(core.tobytes())
    width, height = core.size
    visited = bytearray(len(mask))
    groups = []
    for start, value in enumerate(mask):
        if not value or visited[start]:
            continue
        pending = [start]
        visited[start] = 1
        group = []
        while pending:
            at = pending.pop()
            group.append(at)
            x, y = at % width, at // width
            for dx,dy in ((-1,0),(1,0),(0,-1),(0,1)):
                nx,ny = x+dx,y+dy
                if 0 <= nx < width and 0 <= ny < height:
                    nxt = ny*width+nx
                    if mask[nxt] and not visited[nxt]:
                        visited[nxt] = 1
                        pending.append(nxt)
        groups.append(group)
    minimum = max(16, max(map(len,groups),default=0) * .004)
    for group in groups:
        span_x = max(at % width for at in group) - min(at % width for at in group) + 1
        span_y = max(at // width for at in group) - min(at // width for at in group) + 1
        if len(group) < minimum or (span_y <= 2 and span_x > 8 * span_y):
            for at in group:
                mask[at] = 0
    core = Image.frombytes('L',core.size,bytes(mask))
    image.putalpha(core)
    bounds = core.getbbox()
    if bounds is None:
        raise ValueError('empty sprite')
    image = image.crop(bounds)
    image.putdata([(r,g,b,a) if a else (0,0,0,0) for r,g,b,a in image.getdata()])
    return image


def build(source, output):
    source = Image.open(source)
    output.mkdir(parents=True, exist_ok=True)
    pages = [Image.new('RGBA',(256,256)) for _ in range((len(SPRITES)+3)//4)]
    records = []
    for i, (name, box) in enumerate(SPRITES):
        box = tuple(round(v*source.width/2048) for v in box)
        sprite = clean(source.crop(box))
        sprite.save(output / (name+'.png'))
        ratio = sprite.width / sprite.height
        # Fill the tile. Runtime quad restores the original aspect ratio.
        tile = sprite.resize((124,124), Image.Resampling.NEAREST)
        pages[i//4].paste(tile, ((i%2)*128+2, ((i%4)//2)*128+2))
        records.append(dict(name=name, page=i//4, tile=i%4, radius=ratio/2))
    for i,page in enumerate(pages):
        page.save(output/f'page-{i}.png')
    (output/'pack.rgba').write_bytes(b''.join(p.tobytes() for p in pages))
    (output/'sprites.json').write_text(json.dumps(records,indent=2)+'\n')
    layout = '// Generated by tools/slice_vegetation.py from John v2, not retail art.\n'
    layout += 'const PACK: &[(&str, f32)] = &[\n'
    layout += ''.join(f'    ("{r["name"]}", {r["radius"]:.6f}'.rstrip('0') + '),\n' for r in records)
    (output/'pack_layout.rs').write_text(layout+'];\n')



if __name__ == '__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source',type=Path)
    parser.add_argument('output',type=Path)
    args=parser.parse_args()
    build(args.source,args.output)

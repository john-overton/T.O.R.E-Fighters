//! Scene impostor sources: retail tree, bush, grove, palm and rock shapes
//! from the player's import, with supplied cutouts for every missing species. Retail textures are appended to the scenery's static art
//! pages at runtime; nothing retail is compiled in.
//!
//! Every mesh is normalised to a height of 1 standing on y = 0 (x east,
//! z north before the instance turns it), so an instance sets its height
//! in feet and keeps the mesh's proportions. The retail trees' flat ground
//! shadow quads are dropped. Near cards cast shadows at High and Ultra shadow quality.
//!
//! Vertices are ten floats, the static art layout: position, page uv,
//! page (-1 untextured), normal, then the colour: a palette index for an
//! untextured retail face, or a negative part code for a drawn mesh
//! (`PART_*`), coloured from the instance.

use crate::vegetation::Species;
use std::{collections::BTreeMap, ops::Range};

pub const FLOATS: usize = 10;
/// How a mesh is lit and coloured.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Look {
    /// Leaves: lit mostly from above, so a card seen edge-on to the sun
    /// does not go black.
    Foliage,
    /// Solid: lit by its own normals. Rock and sand.
    Solid,
}

#[derive(Clone, Debug)]
pub struct Mesh {
    pub range: Range<u32>,
    /// Horizontal radius over height.
    pub radius: f32,
    /// Individual height relative to the source shape, including transparent trim.
    pub height_scale: f32,
    pub look: Look,
    /// Recolour a retail texture to the instance's colour by its brightness
    /// (retail rock), with the texture's mean linear colour.
    pub recolour: Option<[f32; 3]>,
    /// Where it came from: a retail shape name or a supplied sprite.
    pub source: String,
    /// Indexed side page, generated by scene preparation and cached locally.
    pub sprite_layer: usize,
    /// Packed generated art uses one of four 128 px cells, with a 2 px gutter.
    pub sprite_tile: Option<u8>,
    /// Top page, grounded height fraction, and opaque half extents over height.
    pub top: [f32; 4],
    /// Individual crowns in a retail grove, before the instance's seeded scale.
    pub crowns: Vec<Crown>,
    pub mean_color: [f32; 3],
}

#[derive(Clone, Debug)]
pub struct Crown {
    pub center: [f32; 2],
    pub half: [f32; 2],
}

pub struct Library {
    pub vertices: Vec<f32>,
    pub meshes: Vec<Mesh>,
    /// Mesh indices for each species, in `Species::ALL` order.
    pub variants: Vec<Vec<u16>>,
}

/// How a retail shape becomes meshes.
#[derive(Clone, Copy, PartialEq, Eq)]
enum Cut {
    /// The whole shape, standing on its lowest point.
    Whole,
    /// The whole shape, standing on its own origin plane (retail rock is
    /// partly buried).
    Buried,
    /// Every plant of a grove as its own independently placed mesh.
    Plants,
}

/// Which retail shapes stand for each species, tried in order. A species
/// with none found uses its supplied-art fallback.
const RETAIL: &[(Species, &[&str], Cut)] = &[
    (Species::Broadleaf, &["TREEA.SH"], Cut::Whole),
    (Species::Autumn, &["TREEB.SH"], Cut::Whole),
    (Species::Dead, &["TREEC.SH"], Cut::Whole),
    (Species::Conifer, &["TREED.SH"], Cut::Whole),
    (Species::Palm, &["PLMGA.SH", "PLMGB.SH"], Cut::Plants),
    (
        Species::PalmGrove,
        &["PLMGA.SH", "PLMGB.SH", "PLMGC.SH"],
        Cut::Plants,
    ),
    (
        Species::Grove,
        &["GROVA.SH", "GROVB.SH", "GROVC.SH", "GROVD.SH"],
        Cut::Plants,
    ),
    (
        Species::PineGrove,
        &["GROVPA.SH", "GROVPB.SH", "GROVPC.SH"],
        Cut::Plants,
    ),
    (
        Species::DryBush,
        &["BUSH1.SH", "BUSH2.SH", "BUSH3.SH"],
        Cut::Whole,
    ),
    (Species::GreenBush, &["BUSH4.SH"], Cut::Whole),
    (Species::Stone, &["ROCK.SH"], Cut::Buried),
    (
        Species::Outcrop,
        &[
            "ROCKA.SH",
            "ROCKB.SH",
            "ROCKC.SH",
            "ROCKD.SH",
            "ROCKE.SH",
            "ROCKBA.SH",
            "ROCKBB.SH",
            "ROCKBC.SH",
            "ROCKBD.SH",
            "ROCKBE.SH",
        ],
        Cut::Buried,
    ),
];

impl Library {
    /// `art` is the import's vegetation art, `resources` the theater's
    /// (its rock shapes). Textures go to `pages` after `first_layer`.
    pub fn build(
        art: &BTreeMap<String, Vec<u8>>,
        resources: &BTreeMap<String, Vec<u8>>,
        palette: &[[u8; 3]; 256],
        pages: &mut Vec<u8>,
        first_layer: impl Fn(&Vec<u8>) -> usize,
    ) -> Self {
        let mut lib = Self {
            vertices: Vec::new(),
            meshes: Vec::new(),
            variants: vec![Vec::new(); Species::ALL.len()],
        };
        let mut images = BTreeMap::new();
        for (species, names, cut) in RETAIL {
            for name in *names {
                let Some(bytes) = art.get(*name).or_else(|| resources.get(*name)) else {
                    continue;
                };
                let rock = matches!(species, Species::Stone | Species::Outcrop);
                let look = if rock { Look::Solid } else { Look::Foliage };
                match retail(
                    bytes,
                    *cut,
                    art,
                    resources,
                    palette,
                    pages,
                    &first_layer,
                    &mut images,
                ) {
                    Ok(meshes) => {
                        for (crown, ((verts, radius, mean), height_scale)) in
                            meshes.into_iter().enumerate()
                        {
                            let recolour = rock.then_some(mean);
                            let source =
                                format!("{}-crown-{:02}", name.trim_end_matches(".SH"), crown + 1);
                            if let Some(id) = lib.meshes.iter().position(|m| m.source == source) {
                                lib.variants[*species as usize].push(id as u16);
                                continue;
                            }
                            lib.push(*species, verts, radius, look, recolour, &source);
                            lib.meshes.last_mut().unwrap().height_scale = height_scale;
                        }
                    }
                    Err(e) => eprintln!("vegetation: {name} unusable: {e}"),
                }
            }
        }
        lib.bake(pages, &first_layer, palette);
        lib
    }

    /// Supplied art fills every missing species, even in retail mode. No code-
    /// drawn tree, shrub or rock survives. Sahara replaces desert equivalents.
    pub fn add_pack(
        &mut self,
        mode: &str,
        region: crate::vegetation::Region,
        palette: &[[u8; 3]; 256],
        pages: &mut Vec<u8>,
        first: usize,
    ) {
        let base_start = pages.len();
        append_rgba(
            include_bytes!("../assets/vegetation/pack.rgba"),
            palette,
            pages,
        );
        let extra_first = first + 8;
        append_rgba(
            include_bytes!("../assets/vegetation/pass5/pack.rgba"),
            palette,
            pages,
        );
        // Side cells keep crop debris from neighbouring sprites in the source
        // sheets (the conifer carries the red bush's ground strip at its top).
        // On an upright card that strip floats above the tree as a flat card.
        clean_side_cells(&mut pages[base_start..]);
        let tropical = region.climate == 3;
        let desert = region.climate == 1;
        for species in Species::ALL {
            let (ids, extra): (&[usize], bool) = match species {
                Species::Dead => (&[8], true),
                Species::Acacia => (&[4, 5], true),
                Species::Palm | Species::PalmGrove if desert => (&[0, 1, 2, 3], true),
                Species::DryBush if desert => (&[7, 9, 11, 12, 14], true),
                Species::GreenBush if desert => (&[6, 13], true),
                Species::Stone if desert => (&[19, 20], true),
                Species::Boulder if desert => (&[17, 18], true),
                Species::Outcrop if desert => (&[15, 16], true),
                Species::Broadleaf | Species::Grove => {
                    (if tropical { &[21] } else { &[9, 11] }, false)
                }
                Species::Autumn => (&[10], false),
                Species::Conifer | Species::PineGrove => (&[15], false),
                Species::Palm | Species::PalmGrove => (&[19, 20], false),
                Species::DryBush => (&[3, 4, 5, 29], false),
                Species::GreenBush => (
                    if tropical {
                        &[22, 23, 24, 25]
                    } else {
                        &[12, 14]
                    },
                    false,
                ),
                Species::Stone => (&[18, 30], false),
                Species::Boulder => (&[17, 27], false),
                Species::Outcrop => (&[16, 26], false),
            };
            let retain = !self.variants[species as usize].is_empty()
                && !extra
                && (mode == "retail"
                    || (mode != "pack"
                        && matches!(
                            species,
                            Species::Conifer
                                | Species::Grove
                                | Species::PineGrove
                                | Species::PalmGrove
                        )));
            if retain {
                continue;
            }
            self.variants[species as usize].clear();
            for &id in ids {
                let (name, radius) = if extra { EXTRA[id] } else { PACK[id] };
                let first_page = if extra { extra_first } else { first };
                let start = base_start + (first_page - first + id / 4) * 65536;
                let cell: Vec<_> = (0..128)
                    .flat_map(|y| {
                        let row = start + (id % 4 / 2 * 128 + y) * 256 + id % 2 * 128;
                        pages[row..row + 128].iter().copied()
                    })
                    .collect();
                let mean = indexed_mean(&cell, palette).unwrap_or([0.; 3]);
                let solid = matches!(
                    species,
                    Species::Stone | Species::Boulder | Species::Outcrop
                );
                self.variants[species as usize].push(self.meshes.len() as u16);
                self.meshes.push(Mesh {
                    range: 0..6,
                    radius,
                    height_scale: 1.,
                    look: if solid { Look::Solid } else { Look::Foliage },
                    recolour: solid.then_some(mean),
                    mean_color: mean,
                    source: format!("supplied/{name}"),
                    sprite_layer: first_page + id / 4,
                    sprite_tile: Some((id % 4) as u8),
                    top: [
                        packed_page(extra_first, if extra { id + 21 } else { id + 42 }),
                        crown_center(&cell, 128, 2., 124.),
                        radius * 1.02 * opaque_width(&cell, 128) / 124.,
                        radius * 1.02 * opaque_width(&cell, 128) / 124.,
                    ],
                    crowns: Vec::new(),
                });
            }
        }
        // A horizontal disk through a conical crown becomes a detached cap
        // as the side card fades. Keep pine silhouettes upright in top modes.
        // Other species retain their existing angle hand-off and artwork.
        for species in [Species::Conifer, Species::PineGrove] {
            for &id in &self.variants[species as usize] {
                let mesh = &mut self.meshes[usize::from(id)];
                if mesh.source.starts_with("supplied/") {
                    mesh.top[2..].fill(0.);
                }
            }
        }
    }

    /// CPU orthographic rasterization during scene preparation. The indexed pages share the
    /// scenery texture array, including its weather palette and transparency.
    fn bake(
        &mut self,
        pages: &mut Vec<u8>,
        first: &impl Fn(&Vec<u8>) -> usize,
        palette: &[[u8; 3]; 256],
    ) {
        let source_first = first(pages);
        let baked = tore_workers::bulk().ordered_map(&self.meshes, 2, |_, mesh| {
            let vertices = &self.vertices
                [mesh.range.start as usize * FLOATS..mesh.range.end as usize * FLOATS];
            (0..4)
                .map(|angle| bake_view(vertices, mesh.radius, angle, pages, source_first, palette))
                .collect::<Vec<_>>()
        });
        let mut cells = Vec::new();
        for (mesh, views) in self.meshes.iter_mut().zip(baked) {
            // One stable side silhouette, just like a supplied sprite. Rotating
            // the camera cannot switch to another source face or a whole row.
            let page = views
                .into_iter()
                .max_by_key(|p| p.iter().filter(|&&v| v != 255).count())
                .unwrap();
            let (side, bounds) = trim_cell(&page, 256, 256);
            let [w, h] = bounds;
            mesh.radius *= w as f32 / h.max(1) as f32;
            mesh.height_scale *= h as f32 / 254.;
            mesh.top = [
                0.,
                crown_center(&side, 128, 2., 124.),
                mesh.radius * 1.02,
                mesh.radius * 1.02,
            ];
            mesh.crowns = vec![Crown {
                center: [0.; 2],
                half: [mesh.top[2], mesh.top[3]],
            }];
            mesh.mean_color = indexed_mean(&side, palette).unwrap_or([0.; 3]);
            if mesh.look == Look::Solid {
                mesh.recolour = indexed_mean(&side, palette);
            }
            let top = if let Some((top, aspect)) =
                crate::vegetation::cache::top_override(&mesh.source, palette)
            {
                // Keep an override's opaque aspect inside the measured crown
                // span instead of stretching wide or narrow tops into squares.
                mesh.top[2] *= aspect.min(1.);
                mesh.top[3] /= aspect.max(1.);
                top
            } else {
                procedural_top(&side)
            };
            cells.push(side);
            cells.push(top);
        }
        let base = first(pages);
        for (id, mesh) in self.meshes.iter_mut().enumerate() {
            mesh.sprite_layer = base + id * 2 / 4;
            mesh.sprite_tile = Some((id * 2 % 4) as u8);
            mesh.top[0] = packed_page(base, id * 2 + 1);
        }
        for chunk in cells.chunks(4) {
            let mut page = vec![255; 65536];
            for (tile, cell) in chunk.iter().enumerate() {
                for y in 0..128 {
                    let start = (tile / 2 * 128 + y) * 256 + tile % 2 * 128;
                    page[start..start + 128].copy_from_slice(&cell[y * 128..(y + 1) * 128]);
                }
            }
            pages.extend(page);
        }
        // All species use the same two triangles. Dimensions and page selection
        // travel with each instance, allowing a single indirect draw.
        self.vertices.clear();
        for [x, y] in [
            [-1., 0.],
            [-1., 1.],
            [1., 1.],
            [-1., 0.],
            [1., 1.],
            [1., 0.],
        ] {
            self.vertices
                .extend([x, y, 0., (x + 1.) * 0.5, 1. - y, 0., 0., 0., 1., 0.]);
        }
        let card = self.vertices.clone();
        self.vertices.extend_from_slice(&card);
        self.vertices.extend_from_slice(&card);
        for mesh in &mut self.meshes {
            mesh.range = 0..6;
        }
    }

    fn push(
        &mut self,
        species: Species,
        verts: Vec<f32>,
        radius: f32,
        look: Look,
        recolour: Option<[f32; 3]>,
        source: &str,
    ) {
        let start = (self.vertices.len() / FLOATS) as u32;
        self.vertices.extend(verts);
        let end = (self.vertices.len() / FLOATS) as u32;
        self.variants[species as usize].push(self.meshes.len() as u16);
        self.meshes.push(Mesh {
            range: start..end,
            radius,
            height_scale: 1.,
            look,
            recolour,
            source: source.to_string(),
            sprite_layer: 0,
            sprite_tile: None,
            top: [0., 0.75, 0., 0.],
            crowns: Vec::new(),
            mean_color: [0.; 3],
        });
    }

    pub fn mesh_for(&self, species: Species, variant: u8) -> u16 {
        let list = &self.variants[species as usize];
        list[usize::from(variant) % list.len()]
    }

    /// One line per species: the meshes it draws and where they came from.
    pub fn report(&self) -> Vec<String> {
        Species::ALL
            .iter()
            .map(|s| {
                let sources: Vec<String> = self.variants[*s as usize]
                    .iter()
                    .map(|&m| {
                        let mesh = &self.meshes[usize::from(m)];
                        format!(
                            "{} ({} tris)",
                            mesh.source,
                            (mesh.range.end - mesh.range.start) / 3
                        )
                    })
                    .collect();
                format!("{s:?}: {}", sources.join(", "))
            })
            .collect()
    }
}

/// Four horizontal views retain the shape's silhouette without runtime mesh work.
fn bake_view(
    vertices: &[f32],
    radius: f32,
    angle: usize,
    pages: &[u8],
    layers: usize,
    palette: &[[u8; 3]; 256],
) -> Vec<u8> {
    let mut out = vec![255u8; 256 * 256];
    let mut depth = vec![f32::NEG_INFINITY; 256 * 256];
    let (sn, cs) = (angle as f32 * std::f32::consts::FRAC_PI_2).sin_cos();
    let radius = radius.max(0.05) * 1.02;
    // Pages may follow other scene textures; locate their logical layer zero.
    let offset = layers * 65536 - pages.len();
    let nearest = |rgb: [u8; 3]| -> u8 {
        (0..255)
            .min_by_key(|&i| {
                (0..3)
                    .map(|k| {
                        let d = i32::from(palette[i][k]) - i32::from(rgb[k]);
                        d * d
                    })
                    .sum::<i32>()
            })
            .unwrap_or(0) as u8
    };
    let parts = [
        nearest([53, 89, 43]),
        nearest([78, 61, 45]),
        nearest([111, 91, 72]),
    ];
    for tri in vertices.chunks_exact(FLOATS * 3) {
        let v: Vec<&[f32]> = tri.chunks_exact(FLOATS).collect();
        let p: Vec<[f32; 3]> = v
            .iter()
            .map(|v| {
                [
                    ((v[0] * cs - v[2] * sn) / radius * 0.5 + 0.5) * 254. + 1.,
                    (1. - v[1]) * 254. + 1.,
                    v[0] * sn + v[2] * cs,
                ]
            })
            .collect();
        let edge = |a: [f32; 3], b: [f32; 3], x: f32, y: f32| {
            (b[0] - a[0]) * (y - a[1]) - (b[1] - a[1]) * (x - a[0])
        };
        let area = edge(p[0], p[1], p[2][0], p[2][1]);
        if area.abs() < 0.0001 {
            continue;
        }
        let bounds = |axis: usize| {
            let lo = p
                .iter()
                .map(|v| v[axis])
                .fold(f32::INFINITY, f32::min)
                .floor()
                .clamp(0., 255.) as usize;
            let hi = p
                .iter()
                .map(|v| v[axis])
                .fold(f32::NEG_INFINITY, f32::max)
                .ceil()
                .clamp(0., 255.) as usize;
            lo..=hi
        };
        for y in bounds(1) {
            for x in bounds(0) {
                let a = edge(p[1], p[2], x as f32 + 0.5, y as f32 + 0.5) / area;
                let b = edge(p[2], p[0], x as f32 + 0.5, y as f32 + 0.5) / area;
                let c = 1. - a - b;
                if a < -0.0001 || b < -0.0001 || c < -0.0001 {
                    continue;
                }
                let blend = |k: usize| a * v[0][k] + b * v[1][k] + c * v[2][k];
                let z = a * p[0][2] + b * p[1][2] + c * p[2][2];
                let at = y * 256 + x;
                if z <= depth[at] {
                    continue;
                }
                let index = if v[0][5] >= 0. {
                    let u = (blend(3) * 256.).floor().clamp(0., 255.) as usize;
                    let w = (blend(4) * 256.).floor().clamp(0., 255.) as usize;
                    let address = v[0][5] as usize * 65536 + w * 256 + u;
                    address
                        .checked_sub(offset)
                        .and_then(|i| pages.get(i))
                        .copied()
                        .unwrap_or(255)
                } else if v[0][9] < 0. {
                    parts[(-v[0][9] - 1.) as usize % 3]
                } else {
                    v[0][9] as u8
                };
                if index != 255 {
                    out[at] = index;
                    depth[at] = z;
                }
            }
        }
    }
    out
}

/// Trim visible bounds into a supplied-pack-sized cell, preserving indexed
/// colours and nearest-neighbour sampling. Bounds also restore world aspect.
pub(crate) fn trim_cell(pixels: &[u8], width: usize, height: usize) -> (Vec<u8>, [usize; 2]) {
    let mut lo = [width, height];
    let mut hi = [0; 2];
    for (i, &p) in pixels.iter().enumerate() {
        if p != 255 {
            lo[0] = lo[0].min(i % width);
            lo[1] = lo[1].min(i / width);
            hi[0] = hi[0].max(i % width + 1);
            hi[1] = hi[1].max(i / width + 1);
        }
    }
    let size = [hi[0].saturating_sub(lo[0]), hi[1].saturating_sub(lo[1])];
    let mut cell = vec![255; 128 * 128];
    if size.contains(&0) {
        return (cell, [1, 1]);
    }
    for y in 0..124 {
        for x in 0..124 {
            cell[(y + 2) * 128 + x + 2] =
                pixels[(lo[1] + y * size[1] / 124) * width + lo[0] + x * size[0] / 124];
        }
    }
    (cell, size)
}

/// Fitted top footprint textured from the broad, leafy part of the imported
/// side. Sampling the crown in two dimensions avoids concentric lathe rings.
fn procedural_top(side: &[u8]) -> Vec<u8> {
    let widths: Vec<_> = side
        .chunks_exact(128)
        .map(|row| opaque_width(row, 128))
        .collect();
    let widest = widths.iter().copied().fold(0., f32::max);
    let broad = |w: &f32| *w > 0. && *w >= widest * 0.45;
    let first = widths.iter().position(broad).unwrap_or(0);
    let last = widths.iter().rposition(broad).unwrap_or(first);
    let rows: Vec<Vec<u8>> = side
        .chunks_exact(128)
        .map(|row| row.iter().copied().filter(|&p| p != 255).collect())
        .collect();
    let mut top = vec![255; 128 * 128];
    for y in 2..126 {
        for x in 2..126 {
            let dx = (x as f32 + 0.5 - 64.) / 62.;
            let dz = (y as f32 + 0.5 - 64.) / 62.;
            // A small irregular outline is fitted, not original crown geometry.
            let angle = dz.atan2(dx);
            let edge = 0.96 + 0.025 * (angle * 7.).sin() + 0.015 * (angle * 11.).cos();
            if dx.hypot(dz) > edge {
                continue;
            }
            let row = first + (y - 2) * (last - first + 1) / 124;
            let colors = &rows[row.min(127)];
            if !colors.is_empty() {
                top[y * 128 + x] = colors[(x - 2) * colors.len() / 124];
            }
        }
    }
    top
}

/// A complete local PNG, bounded before decoding. This reuses the app's small
/// PNG reader and adds no dependency. The resulting page follows cutout alpha.
pub(crate) fn override_cell(
    bytes: &[u8],
    palette: &[[u8; 3]; 256],
) -> Result<(Vec<u8>, f32), String> {
    let dimensions = bytes.get(16..24).ok_or("missing PNG dimensions")?;
    let w = u32::from_be_bytes(dimensions[..4].try_into().unwrap());
    let h = u32::from_be_bytes(dimensions[4..].try_into().unwrap());
    if !(1..=2048).contains(&w) || !(1..=2048).contains(&h) {
        return Err("top PNG must be 1 to 2048 pixels on each axis".into());
    }
    let image = crate::widgets::png_read::decode_rows(bytes, 2048, 2048)?;
    let mut lo = [image.width, image.rows];
    let mut hi = [0; 2];
    for (i, pixel) in image.rgba.chunks_exact(4).enumerate() {
        if pixel[3] >= 128 {
            lo[0] = lo[0].min(i % image.width);
            lo[1] = lo[1].min(i / image.width);
            hi[0] = hi[0].max(i % image.width + 1);
            hi[1] = hi[1].max(i / image.width + 1);
        }
    }
    if hi.contains(&0) {
        return Err("top PNG is fully transparent".into());
    }
    // Quantize only the samples the GPU will use, not millions of pixels in
    // an authoring image. The trim and nearest-neighbour result is identical.
    let mut colors = BTreeMap::new();
    let mut cell = vec![255; 128 * 128];
    for y in 0..124 {
        for x in 0..124 {
            let sx = lo[0] + x * (hi[0] - lo[0]) / 124;
            let sy = lo[1] + y * (hi[1] - lo[1]) / 124;
            let pixel = &image.rgba[(sy * image.width + sx) * 4..][..4];
            if pixel[3] < 128 {
                continue;
            }
            let rgb = [pixel[0], pixel[1], pixel[2]];
            cell[(y + 2) * 128 + x + 2] = *colors.entry(rgb).or_insert_with(|| {
                (0..255)
                    .min_by_key(|&i| {
                        (0..3)
                            .map(|k| (i32::from(palette[i][k]) - i32::from(rgb[k])).pow(2))
                            .sum::<i32>()
                    })
                    .unwrap() as u8
            });
        }
    }
    Ok((cell, (hi[0] - lo[0]) as f32 / (hi[1] - lo[1]) as f32))
}

/// Mean visible linear albedo of an actual baked sprite, not its source sheet.
fn indexed_mean(pixels: &[u8], palette: &[[u8; 3]; 256]) -> Option<[f32; 3]> {
    let mut sum = [0.; 3];
    let mut count = 0.;
    for &index in pixels {
        if index == 255 {
            continue;
        }
        let rgb = crate::vegetation::lin(palette[usize::from(index)]);
        for k in 0..3 {
            sum[k] += rgb[k];
        }
        count += 1.;
    }
    if count == 0. {
        return None;
    }
    let mean = sum.map(|x| x / count);
    (mean.iter().sum::<f32>() > 0.0001).then_some(mean)
}


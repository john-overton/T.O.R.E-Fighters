/// A retail shape as normalised meshes: vertices, radius over height, and
/// the mean linear colour of its textures.
#[allow(clippy::too_many_arguments)]
fn retail(
    bytes: &[u8],
    cut: Cut,
    art: &BTreeMap<String, Vec<u8>>,
    resources: &BTreeMap<String, Vec<u8>>,
    palette: &[[u8; 3]; 256],
    pages: &mut Vec<u8>,
    first_layer: &impl Fn(&Vec<u8>) -> usize,
    images: &mut Images,
) -> crate::AppResult<Vec<CrownSource>> {
    let shape = tore_formats::shape::Shape::scenery(bytes)?;
    if shape.faces.is_empty() {
        return Ok(Vec::new());
    }
    let mut lo = [f32::INFINITY; 3];
    let mut hi = [f32::NEG_INFINITY; 3];
    for p in shape.faces.iter().flat_map(|f| &f.positions) {
        for k in 0..3 {
            lo[k] = lo[k].min(p[k]);
            hi[k] = hi[k].max(p[k]);
        }
    }
    let full = (hi[2] - lo[2]).max(1e-3);
    // A flat face at the very bottom is a painted ground shadow.
    let ground =
        |f: &tore_formats::shape::Face| f.positions.iter().all(|p| p[2] <= lo[2] + full * 0.03);
    let kept: Vec<&tore_formats::shape::Face> = shape
        .faces
        .iter()
        .filter(|f| f.positions.len() >= 3 && !ground(f))
        .collect();
    if kept.is_empty() {
        return Ok(Vec::new());
    }
    let groups = if cut == Cut::Plants {
        plant_groups(&kept)
    } else {
        vec![kept]
    };
    let mut out = Vec::new();
    for group in groups {
        if let Some(mesh) = normalise(
            &group,
            cut,
            art,
            resources,
            palette,
            pages,
            first_layer,
            images,
        )? {
            let (_, height) = plant_frame(&group);
            out.push((mesh, height / full));
        }
    }
    Ok(out)
}

/// Splits a grove into plants: faces whose centres stand within 18 source units
/// of each other belong together. The existing fitted palm grouping rule.
fn plant_groups<'a>(
    faces: &[&'a tore_formats::shape::Face],
) -> Vec<Vec<&'a tore_formats::shape::Face>> {
    let centre = |f: &tore_formats::shape::Face| {
        let n = f.positions.len() as f32;
        let s = f
            .positions
            .iter()
            .fold([0f32; 2], |a, p| [a[0] + p[0], a[1] + p[1]]);
        [s[0] / n, s[1] / n]
    };
    let centres: Vec<[f32; 2]> = faces.iter().map(|f| centre(f)).collect();
    let mut parent: Vec<usize> = (0..faces.len()).collect();
    fn root(parent: &mut [usize], mut i: usize) -> usize {
        while parent[i] != i {
            parent[i] = parent[parent[i]];
            i = parent[i];
        }
        i
    }
    for i in 0..faces.len() {
        for j in i + 1..faces.len() {
            let d = (centres[i][0] - centres[j][0]).hypot(centres[i][1] - centres[j][1]);
            if d < 18. {
                let (a, b) = (root(&mut parent, i), root(&mut parent, j));
                parent[a] = b;
            }
        }
    }
    let mut groups: BTreeMap<usize, Vec<&tore_formats::shape::Face>> = BTreeMap::new();
    for (i, f) in faces.iter().enumerate() {
        let r = root(&mut parent, i);
        groups.entry(r).or_default().push(f);
    }
    groups.into_values().collect()
}

fn plant_frame(faces: &[&tore_formats::shape::Face]) -> ([f32; 2], f32) {
    let mut lo = [f32::INFINITY; 3];
    let mut hi = [f32::NEG_INFINITY; 3];
    for p in faces.iter().flat_map(|f| &f.positions) {
        for k in 0..3 {
            lo[k] = lo[k].min(p[k]);
            hi[k] = hi[k].max(p[k]);
        }
    }
    (
        [(lo[0] + hi[0]) * 0.5, (lo[1] + hi[1]) * 0.5],
        (hi[2] - lo[2]).max(1e-3),
    )
}

/// Alpha bounds, not the padded source quad, define the visible crown width.
fn opaque_width(pixels: &[u8], stride: usize) -> f32 {
    let mut lo = stride;
    let mut hi = 0;
    for (i, &pixel) in pixels.iter().enumerate() {
        if pixel != 255 {
            lo = lo.min(i % stride);
            hi = hi.max(i % stride + 1);
        }
    }
    hi.saturating_sub(lo) as f32
}

#[allow(clippy::too_many_arguments)]
fn normalise(
    kept: &[&tore_formats::shape::Face],
    cut: Cut,
    art: &BTreeMap<String, Vec<u8>>,
    resources: &BTreeMap<String, Vec<u8>>,
    palette: &[[u8; 3]; 256],
    pages: &mut Vec<u8>,
    first_layer: &impl Fn(&Vec<u8>) -> usize,
    images: &mut Images,
) -> crate::AppResult<Option<Built>> {
    let mut base = f32::INFINITY;
    let mut top = f32::NEG_INFINITY;
    let mut xl = f32::INFINITY;
    let mut xh = f32::NEG_INFINITY;
    let mut yl = f32::INFINITY;
    let mut yh = f32::NEG_INFINITY;
    for p in kept.iter().flat_map(|f| &f.positions) {
        base = base.min(p[2]);
        top = top.max(p[2]);
        xl = xl.min(p[0]);
        xh = xh.max(p[0]);
        yl = yl.min(p[1]);
        yh = yh.max(p[1]);
    }
    if cut == Cut::Buried {
        base = 0.;
    }
    let height = (top - base).max(1e-3);
    let cx = (xl + xh) * 0.5;
    let cy = (yl + yh) * 0.5;
    let s = 1. / height;
    let mut out = Vec::new();
    let mut mean = [0f32; 4];
    let mut radius = 0f32;
    for &face in kept {
        let image = if face.texture.is_empty() || face.uv.is_empty() {
            None
        } else {
            let name = face.texture.to_ascii_uppercase();
            if !images.contains_key(&name) {
                let loaded = match art.get(&name).or_else(|| resources.get(&name)) {
                    Some(bytes) => {
                        let pic = tore_formats::Pic::parse(bytes)?;
                        let mut sum = [0f32; 4];
                        for (p, m) in pic.pixels.iter().zip(&pic.mask) {
                            if *m && *p != 255 {
                                let c = crate::vegetation::lin(palette[usize::from(*p)]);
                                sum[0] += c[0];
                                sum[1] += c[1];
                                sum[2] += c[2];
                                sum[3] += 1.;
                            }
                        }
                        let n = sum[3].max(1.);
                        let first = first_layer(pages);
                        let image = crate::static_art::Image::append(&pic, pages, first)?;
                        Some((image, [sum[0] / n, sum[1] / n, sum[2] / n]))
                    }
                    None => None,
                };
                images.insert(name.clone(), loaded);
            }
            images[&name]
        };
        if !face.texture.is_empty() && image.is_none() {
            return Err(format!("missing vegetation cutout {}", face.texture).into());
        }
        let local = |p: [f32; 3]| [(p[0] - cx) * s, (p[2] - base) * s, (p[1] - cy) * s];
        let a = local(face.positions[0]);
        let mut normal = [0f32; 3];
        for w in face.positions[1..].windows(2) {
            let b = local(w[0]);
            let c = local(w[1]);
            let n = cross(sub(b, a), sub(c, a));
            normal = [normal[0] + n[0], normal[1] + n[1], normal[2] + n[2]];
        }
        let normal = normalize(normal);
        for triangle in 1..face.positions.len() - 1 {
            let mut points = [[0f32; FLOATS]; 3];
            for (slot, i) in [0, triangle, triangle + 1].into_iter().enumerate() {
                let p = local(face.positions[i]);
                radius = radius.max(p[0].hypot(p[2]));
                let uv = face.uv.get(i).copied().unwrap_or([0.; 2]);
                let uv = image.map_or([0., 0.], |(image, _)| {
                    [uv[0] + 0.5, image.height as f32 - 0.5 - uv[1]]
                });
                points[slot] = [
                    p[0],
                    p[1],
                    p[2],
                    uv[0],
                    uv[1],
                    -1.,
                    normal[0],
                    normal[1],
                    normal[2],
                    f32::from(face.colors.get(i).copied().unwrap_or(0)),
                ];
            }
            match image {
                Some((image, m)) => {
                    image.triangle(points, &mut out, usize::MAX)?;
                    mean = [mean[0] + m[0], mean[1] + m[1], mean[2] + m[2], mean[3] + 1.];
                }
                None => out.extend(points.into_iter().flatten()),
            }
        }
    }
    let n = mean[3].max(1.);
    if out.is_empty() {
        return Ok(None);
    }
    Ok(Some((
        out,
        radius.max(0.05),
        [mean[0] / n, mean[1] / n, mean[2] / n],
    )))
}

fn sub(a: [f32; 3], b: [f32; 3]) -> [f32; 3] {
    [a[0] - b[0], a[1] - b[1], a[2] - b[2]]
}

fn cross(u: [f32; 3], v: [f32; 3]) -> [f32; 3] {
    [
        u[1] * v[2] - u[2] * v[1],
        u[2] * v[0] - u[0] * v[2],
        u[0] * v[1] - u[1] * v[0],
    ]
}

fn normalize(n: [f32; 3]) -> [f32; 3] {
    let l = (n[0] * n[0] + n[1] * n[1] + n[2] * n[2]).sqrt();
    if l < 1e-8 {
        [0., 1., 0.]
    } else {
        [n[0] / l, n[1] / l, n[2] / l]
    }
}

/// A flat-shaded triangle in a drawn part.
/// Runs `drop_detached_debris` on every side cell of the two supplied packs,
/// given as their appended indexed pages (the v2 pack's 8, then pass 5's).
fn clean_side_cells(pages: &mut [u8]) {
    let cells = PACK.iter().enumerate().chain(
        EXTRA
            .iter()
            .enumerate()
            .map(|(id, sprite)| (32 + id, sprite)),
    );
    for (slot, (name, _)) in cells {
        if is_side_sprite(name) {
            let page = slot / 4 * 65536;
            drop_detached_debris(&mut pages[page..page + 65536], slot % 4);
        }
    }
}

/// Supplied side views stand upright; top views (`top_*`, `sahara_top_*`)
/// lie flat and may legitimately hold separate crowns or stones.
fn is_side_sprite(name: &str) -> bool {
    !name.starts_with("top_") && !name.starts_with("sahara_top_")
}

/// The 8-connected opaque components of one 128 px cell of a 256 px indexed
/// page, as (pixel indices within the page, top row, bottom row).
fn cell_components(page: &[u8], tile: usize) -> Vec<(Vec<usize>, usize, usize)> {
    let (cx, cy) = (tile % 2 * 128, tile / 2 * 128);
    let mut seen = vec![false; 128 * 128];
    let mut out = Vec::new();
    for start in 0..128 * 128 {
        if seen[start] || page[(cy + start / 128) * 256 + cx + start % 128] == 255 {
            continue;
        }
        seen[start] = true;
        let mut pending = vec![start];
        let mut pixels = Vec::new();
        let (mut top, mut bottom) = (127, 0);
        while let Some(at) = pending.pop() {
            let (x, y) = (at % 128, at / 128);
            top = top.min(y);
            bottom = bottom.max(y);
            pixels.push((cy + y) * 256 + cx + x);
            for ny in y.saturating_sub(1)..=(y + 1).min(127) {
                for nx in x.saturating_sub(1)..=(x + 1).min(127) {
                    let next = ny * 128 + nx;
                    if !seen[next] && page[(cy + ny) * 256 + cx + nx] != 255 {
                        seen[next] = true;
                        pending.push(next);
                    }
                }
            }
        }
        out.push((pixels, top, bottom));
    }
    out
}

/// Clears opaque islands that cannot belong to an upright plant or rock: any
/// lying wholly above or below the main body's rows (crop strips from the
/// sprite above or below in the source sheet), and specks under 1% of the
/// main body touching the cell's usable border (side-neighbour bleed).
/// Separate stones and leaves beside the main body stay. Agent rule,
/// 2026-10-19, for John's floating pine card report.
fn drop_detached_debris(page: &mut [u8], tile: usize) {
    let parts = cell_components(page, tile);
    let Some(main) = parts.iter().max_by_key(|p| p.0.len()) else {
        return;
    };
    let (size, top, bottom) = (main.0.len(), main.1, main.2);
    let (cx, cy) = (tile % 2 * 128, tile / 2 * 128);
    let mut clear = Vec::new();
    for (pixels, t, b) in &parts {
        let outside = *b < top || *t > bottom;
        let edge = pixels.iter().any(|&at| {
            let (x, y) = (at % 256 - cx, at / 256 - cy);
            x <= 2 || y <= 2 || x >= 125 || y >= 125
        });
        if outside || (edge && pixels.len() * 100 < size) {
            clear.extend_from_slice(pixels);
        }
    }
    for at in clear {
        page[at] = 255;
    }
}

fn packed_page(first: usize, id: usize) -> f32 {
    -((first * 4 + id + 1) as f32)
}
/// Width-weighted centre of the broad opaque crown, excluding its narrow
/// trunk. The 45% row-width threshold is fitted, independent of view angle.
fn crown_center(pixels: &[u8], stride: usize, gutter: f32, extent: f32) -> f32 {
    let widths: Vec<_> = pixels
        .chunks_exact(stride)
        .map(|row| row.iter().filter(|&&p| p != 255).count())
        .collect();
    let widest = widths.iter().copied().max().unwrap_or(0) as f32;
    let mut sum = 0.;
    let mut weight = 0.;
    for (y, &n) in widths.iter().enumerate() {
        if n > 0 && n as f32 >= widest * 0.45 {
            sum += (1. - (y as f32 + 0.5 - gutter) / extent) * n as f32;
            weight += n as f32;
        }
    }
    if weight > 0. {
        (sum / weight).clamp(0.05, 0.95)
    } else {
        0.5
    }
}
fn append_rgba(rgba: &[u8], palette: &[[u8; 3]; 256], pages: &mut Vec<u8>) {
    let mut lookup = BTreeMap::new();
    for pixel in rgba.chunks_exact(4) {
        if pixel[3] < 128 {
            pages.push(255);
            continue;
        }
        let rgb: [u8; 3] = std::array::from_fn(|k| (f32::from(pixel[k]) * 0.78) as u8);
        pages.push(*lookup.entry(rgb).or_insert_with(|| {
            (0..255)
                .min_by_key(|&i| {
                    (0..3)
                        .map(|k| (i32::from(palette[i][k]) - i32::from(rgb[k])).pow(2))
                        .sum::<i32>()
                })
                .unwrap_or(0) as u8
        }));
    }
}

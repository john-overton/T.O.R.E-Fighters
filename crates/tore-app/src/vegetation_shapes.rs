//! Original text-generated vegetation, encoded as material IDs and shading.
//! No retail shape, texture, top override or rasterizer is used here.
//! Every quad stands at y = 0; placement uses tore_world::grounding.

use crate::vegetation::Species;
use std::ops::Range;

pub const FLOATS: usize = 10;
/// How a mesh is lit and coloured.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Look {
    /// Leaves: lit mostly from above, so a card seen edge-on to the sun
    /// does not go black.
    Foliage,
    /// Solid: lit by its own normals. Rock and sand.
    Solid,
}

#[derive(Clone, Debug)]
pub struct Mesh {
    pub range: Range<u32>,
    /// Horizontal radius over height.
    pub radius: f32,
    /// Individual height relative to the source shape, including transparent trim.
    pub height_scale: f32,
    pub look: Look,
    /// Theater bark colour in linear RGB, independent of leaf tint.
    pub recolour: Option<[f32; 3]>,
    /// Original text-generated sprite identity.
    pub source: String,
    /// Indexed side page, generated by scene preparation and cached locally.
    pub sprite_layer: usize,
    /// Packed generated art uses one of four 128 px cells, with a 2 px gutter.
    pub sprite_tile: Option<u8>,
    /// Top page, grounded height fraction, and opaque half extents over height.
    pub top: [f32; 4],
    /// One crown per independently placed plant.
    pub crowns: Vec<Crown>,
    pub mean_color: [f32; 3],
}

#[derive(Clone, Debug)]
pub struct Crown {
    pub center: [f32; 2],
    pub half: [f32; 2],
}

pub struct Library {
    pub vertices: Vec<f32>,
    pub meshes: Vec<Mesh>,
    /// Mesh indices for each species, in `Species::ALL` order.
    pub variants: Vec<Vec<u16>>,
}

struct Sprite {
    name: &'static str,
    kind: &'static str,
    side: usize,
    top: usize,
    radius: f32,
    top_aspect: f32,
}
include!("../assets/vegetation/pack_layout.rs");
pub const MATERIALS: &[u8] = include_bytes!("../assets/vegetation/pack.materials");

impl Library {
    pub fn build(region: crate::vegetation::Region, pages: &mut Vec<u8>, first: usize) -> Self {
        let mut vertices = Vec::new();
        for [x, y] in [
            [-1., 0.],
            [-1., 1.],
            [1., 1.],
            [-1., 0.],
            [1., 1.],
            [1., 0.],
        ] {
            vertices.extend([x, y, 0., (x + 1.) * 0.5, 1. - y, 0., 0., 0., 1., 0.]);
        }
        let card = vertices.clone();
        vertices.extend_from_slice(&card);
        vertices.extend_from_slice(&card);
        pages.extend_from_slice(MATERIALS);
        let bark = crate::vegetation::lin(match region.climate {
            1 => [116, 91, 60],
            2 => [95, 88, 76],
            3 => [88, 69, 48],
            _ => [102, 78, 53],
        });
        let meshes = SPRITES
            .iter()
            .map(|sprite| {
                let side = cell(MATERIALS, sprite.side);
                let top_x = sprite.radius * 1.02 * sprite.top_aspect.min(1.);
                let top_z = sprite.radius * 1.02 / sprite.top_aspect.max(1.);
                let solid = matches!(sprite.kind, "stone" | "boulder" | "outcrop" | "desert_rock");
                // Integrated material weights let distant canopy use the same colours.
                let mut mean = [0.; 3];
                let mut count = 0.;
                for &p in &side {
                    if p == 255 {
                        continue;
                    }
                    count += 1.;
                    let material = (p / 32).min(2) as usize;
                    mean[material] += shading(p);
                }
                if count > 0. {
                    for m in &mut mean {
                        *m /= count;
                    }
                }
                Mesh {
                    range: 0..6,
                    radius: sprite.radius,
                    height_scale: 1.,
                    look: if solid { Look::Solid } else { Look::Foliage },
                    recolour: Some(bark),
                    source: format!("original/{}", sprite.name),
                    sprite_layer: first + sprite.side / 4,
                    sprite_tile: Some((sprite.side % 4) as u8),
                    top: [
                        -((first * 4 + sprite.top + 1) as f32),
                        crown_center(&side, 128, 2., 124.),
                        top_x,
                        top_z,
                    ],
                    crowns: vec![Crown {
                        center: [0.; 2],
                        half: [top_x, top_z],
                    }],
                    mean_color: mean,
                }
            })
            .collect();
        let variants = Species::ALL
            .iter()
            .map(|species| {
                let kinds: &[&str] = match species {
                    Species::Broadleaf | Species::Grove if region.climate == 3 => &["jungle_tree"],
                    Species::Broadleaf | Species::Grove => &["broadleaf", "birch"],
                    Species::Autumn => &["broadleaf", "birch"],
                    Species::Dead => &["dead"],
                    Species::Conifer | Species::PineGrove => &["conifer"],
                    Species::Palm | Species::PalmGrove => &["palm"],
                    Species::Acacia => &["acacia"],
                    Species::DryBush => &["dry_bush", "dry_scrub"],
                    Species::GreenBush if region.climate == 1 => &["yucca", "green_bush"],
                    Species::GreenBush if region.climate == 3 => {
                        &["fern", "banana", "tropical_shrub"]
                    }
                    Species::GreenBush => &["green_bush"],
                    Species::Stone => &["stone"],
                    Species::Boulder => &["boulder"],
                    Species::Outcrop if region.climate == 1 => &["desert_rock"],
                    Species::Outcrop => &["outcrop"],
                };
                SPRITES
                    .iter()
                    .enumerate()
                    .filter(|(_, s)| kinds.contains(&s.kind))
                    .map(|(id, _)| id as u16)
                    .collect()
            })
            .collect();
        Self {
            vertices,
            meshes,
            variants,
        }
    }

    pub fn mesh_for(&self, species: Species, variant: u8) -> u16 {
        let list = &self.variants[species as usize];
        list[usize::from(variant) % list.len()]
    }

    pub fn report(&self) -> Vec<String> {
        Species::ALL
            .iter()
            .map(|s| {
                format!(
                    "{s:?}: {}",
                    self.variants[*s as usize]
                        .iter()
                        .map(|&id| self.meshes[usize::from(id)].source.as_str())
                        .collect::<Vec<_>>()
                        .join(", ")
                )
            })
            .collect()
    }
}

impl Mesh {
    pub fn mean_tinted(&self, tint: [f32; 3]) -> [f32; 3] {
        let bark = self.recolour.unwrap_or([0.; 3]);
        std::array::from_fn(|k| {
            self.mean_color[0] * tint[k]
                + self.mean_color[1] * bark[k]
                + self.mean_color[2] * tint[k]
        })
    }
}

pub fn shading(pixel: u8) -> f32 {
    0.25 + 1.25 * f32::from(pixel % 32) / 31.
}

pub fn cell(pages: &[u8], slot: usize) -> Vec<u8> {
    let page = slot / 4 * 65536;
    (0..128)
        .flat_map(|y| {
            let at = page + (slot % 4 / 2 * 128 + y) * 256 + slot % 2 * 128;
            pages[at..at + 128].iter().copied()
        })
        .collect()
}

fn crown_center(pixels: &[u8], stride: usize, gutter: f32, extent: f32) -> f32 {
    let widths: Vec<_> = pixels
        .chunks_exact(stride)
        .map(|row| row.iter().filter(|&&p| p != 255).count())
        .collect();
    let widest = widths.iter().copied().max().unwrap_or(0) as f32;
    let mut sum = 0.;
    let mut weight = 0.;
    for (y, &n) in widths.iter().enumerate() {
        if n > 0 && n as f32 >= widest * 0.45 {
            sum += (1. - (y as f32 + 0.5 - gutter) / extent) * n as f32;
            weight += n as f32;
        }
    }
    if weight > 0. {
        (sum / weight).clamp(0.05, 0.95)
    } else {
        0.5
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn all_species_have_three_original_pairs_in_every_climate() {
        for code in ["UKR", "TVIET", "EGY", "KURILE"] {
            let mut pages = vec![255; 65536];
            let lib = Library::build(crate::vegetation::region(code), &mut pages, 1);
            assert_eq!(lib.vertices.len(), 18 * FLOATS);
            assert_eq!(lib.meshes.len(), 54);
            for species in Species::ALL {
                assert!(lib.variants[species as usize].len() >= 3);
                for &id in &lib.variants[species as usize] {
                    let mesh = &lib.meshes[usize::from(id)];
                    assert!(mesh.source.starts_with("original/"));
                    assert_eq!(mesh.crowns.len(), 1);
                    assert!((0.05..=0.95).contains(&mesh.top[1]));
                    assert!(mesh.top[2] > 0. && mesh.top[3] > 0.);
                    assert_eq!(mesh.height_scale, 1.);
                    for slot in [
                        mesh.sprite_layer * 4 + usize::from(mesh.sprite_tile.unwrap()),
                        (-mesh.top[0] - 1.) as usize,
                    ] {
                        let pixels = cell(&pages, slot);
                        assert!(pixels.iter().any(|&p| p != 255));
                        for (at, p) in pixels.iter().enumerate() {
                            assert!(*p == 255 || *p < 128);
                            if at % 128 < 2 || at % 128 >= 126 || at / 128 < 2 || at / 128 >= 126 {
                                assert_eq!(*p, 255);
                            }
                        }
                    }
                }
            }
        }
    }

    #[test]
    fn top_height_is_inside_the_visual_crown_not_its_roof() {
        let mut pixels = vec![255; 100 * 100];
        for y in 10..50 {
            for x in 20..80 {
                pixels[y * 100 + x] = 1;
            }
        }
        for y in 50..100 {
            for x in 48..52 {
                pixels[y * 100 + x] = 33;
            }
        }
        assert!((crown_center(&pixels, 100, 0., 100.) - 0.7).abs() < 0.001);
    }
}

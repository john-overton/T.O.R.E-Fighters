//! Per-store motor, control class and calibration references. Authored data only.
//! Field provenance and conditional anchors: docs/formats/missile-energy-data.md.
/// Authored game control budgets, never anchor-fitted timers.
/// The original values are John's; ShortGround reuses 30 s under Phase 2.6 permission.
/// BoostGlide retains 600 s; ShortCruise shares 300 s under Phase 2.8 permission.
/// Medium/long air classes also explicitly include the R-27 IR variants.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[repr(u8)]
pub enum ControlClass {
    ShortIr,
    MediumAir,
    LongAir,
    Cruise,
    FastGround,
    Command,
    SurfaceIr,
    SurfaceRadar,
    SurfaceRadarLong,
    ShortGround,
    BoostGlide,
    ShortCruise,
}
impl ControlClass {
    pub const fn seconds(self) -> f64 {
        match self {
            Self::ShortIr => 20.,
            Self::MediumAir | Self::SurfaceRadar => 70.,
            Self::LongAir => 180.,
            Self::Cruise | Self::BoostGlide => 600.,
            Self::ShortCruise => 300.,
            Self::FastGround => 90.,
            Self::Command | Self::ShortGround => 30.,
            Self::SurfaceIr => 25.,
            Self::SurfaceRadarLong => 120.,
        }
    }
    pub const fn air_target(self) -> bool {
        !matches!(
            self,
            Self::Cruise
                | Self::ShortCruise
                | Self::BoostGlide
                | Self::FastGround
                | Self::Command
                | Self::ShortGround
        )
    }
    pub const fn tail_floor_km(self) -> Option<f64> {
        match self {
            Self::ShortIr => Some(1.5),
            Self::MediumAir => Some(3.),
            Self::LongAir => Some(5.),
            _ => None,
        }
    }
}

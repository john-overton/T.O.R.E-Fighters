#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn every_reviewed_powered_store_has_one_valid_motor() {
        for source in crate::missile_data::REFERENCES
            .iter()
            .map(|r| r.source)
            .chain(crate::missile_data::FALLBACKS.iter().map(|r| r.source))
        {
            assert_eq!(
                MOTORS.iter().filter(|m| m.source == source).count(),
                1,
                "{source}"
            );
            let m = motor(source).unwrap();
            assert!(m.control_class.seconds() > 0.);
            assert!(!m.guidance_evidence.is_empty());
            assert!(m.ignition_seconds.is_none_or(|s| s.is_finite() && s >= 0.));
            assert!((0.0..1.0).contains(&m.propellant_fraction));
            assert!(m.boost_seconds >= 0. && m.sustain_seconds >= 0., "{source}");
            assert!(m.boost_seconds + m.sustain_seconds > 0., "{source}");
            assert!(m.boost_seconds > 0. || m.boost_share == 0., "{source}");
            assert!((0.0..=1.0).contains(&m.boost_share));
            assert!(m.sustain_seconds > 0. || m.boost_share == 1.);
        }
    }
}

/// Unresolved real identities keep runtime decoded mass/range and class diameter.
/// Only an authored drag fit is stored here; no public variant is invented.
#[derive(Clone, Copy, Debug)]
pub struct Fallback {
    pub source: &'static str,
    pub drag_scale: f64,
}
pub const FALLBACKS: &[Fallback] = &[
    Fallback {
        source: "AS15.JT",
        drag_scale: 1.00000000,
    },
    Fallback {
        source: "AT12.JT",
        drag_scale: 0.75000000,
    },
];
pub fn fallback(source: &str) -> Option<&'static Fallback> {
    FALLBACKS.iter().find(|r| r.source == source)
}

pub fn reference(source: &str) -> Option<&'static Reference> {
    REFERENCES.iter().find(|row| row.source == source)
}

/// Stable table identity for input tapes. Not a cryptographic media digest.
pub fn fingerprint() -> u64 {
    let mut hash = fingerprint_of(REFERENCES);
    for row in FALLBACKS {
        for byte in row
            .source
            .bytes()
            .chain([0])
            .chain(row.drag_scale.to_bits().to_le_bytes())
        {
            hash = (hash ^ u64::from(byte)).wrapping_mul(0x100000001b3);
        }
    }
    hash
}
fn fingerprint_of(rows: &[Reference]) -> u64 {
    let mut hash = 0xcbf29ce484222325u64;
    let mut add = |bytes: &[u8]| {
        for byte in bytes {
            hash = (hash ^ u64::from(*byte)).wrapping_mul(0x100000001b3);
        }
    };
    for row in rows {
        add(row.source.as_bytes());
        add(&[0]);
        for value in [row.mass_kg, row.diameter_m, row.range_km, row.drag_scale] {
            add(&value.to_bits().to_le_bytes());
        }
        add(&[u8::from(row.span_m.is_some())]);
        if let Some(span) = row.span_m {
            add(&span.to_le_bytes());
        }
        add(&[u8::from(row.imaging)]);
        for value in [row.structural_g, row.tracking_deg_s, row.fov_half_deg] {
            add(&[u8::from(value.is_some())]);
            if let Some(value) = value {
                add(&value.to_bits().to_le_bytes());
            }
        }
    }
    hash
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn a_changed_physical_parameter_changes_the_tape_identity() {
        let mut row = REFERENCES[0];
        let before = fingerprint_of(&[row]);
        row.mass_kg += 0.001;
        assert_ne!(before, fingerprint_of(&[row]));
        assert_ne!(fingerprint(), 0);
    }
    #[test]
    fn references_are_positive_unique_and_identified() {
        for (i, row) in REFERENCES.iter().enumerate() {
            assert!(
                row.span_m
                    .is_none_or(|s| s.is_finite() && s >= row.diameter_m)
            );
            assert!(!row.span_evidence.is_empty());
            assert!(row.mass_kg > 0. && row.diameter_m > 0. && row.range_km > 0.);
            assert!(!row.dimensions_evidence.is_empty() && !row.range_evidence.is_empty());
            assert!(
                !REFERENCES[..i]
                    .iter()
                    .any(|prior| prior.source == row.source)
            );
        }
        assert!(reference("AIM120D.JT").is_none());
    }
}
